import fs from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import type { Skill } from '../src/skills/store.js';
import type { SpecFlow, SpecSegment, SpecStep } from '../src/spec/ir.js';
import { LiftError, isOwnedFlowFile, liftFlowFile } from '../src/spec/lift.js';

// --- test-local builder for the emit.ts layout (contract section 3) -------
//
// emit.ts is being written concurrently by another agent, so lift's own
// tests cannot depend on it for the primary round-trip check. This helper
// reproduces only what liftFlowFile actually reads: the header comment, the
// begin/end region markers, and `export const FLOW = <json>;` inside them.
// It deliberately omits the rest of the generated file (Vars/Outputs types,
// steps object, runFlow) since lift never looks at that TypeScript body.
function buildFlowFileText(
  spec: SpecFlow,
  opts: { omitBegin?: boolean; omitEnd?: boolean; header?: boolean; handEditedJson?: string } = {},
): string {
  const { omitBegin, omitEnd, header = true, handEditedJson } = opts;
  const lines: string[] = [];
  if (header) {
    lines.push('// @sitelooper-flow v1');
    lines.push(`// Generated by sitelooper from flow "${spec.name}" — do not edit by hand.`);
    lines.push('// Repair drift with `sitelooper repair <this file>`; the FLOW constant below is the source of truth.');
  }
  lines.push("import { expect, type Page } from '@playwright/test';");
  lines.push('');
  if (!omitBegin) lines.push('// @sitelooper-flow-begin');
  const json = handEditedJson ?? JSON.stringify(spec, null, 2);
  lines.push(`export const FLOW = ${json};`);
  if (!omitEnd) lines.push('// @sitelooper-flow-end');
  lines.push('');
  lines.push(`export type Vars = { ${spec.vars.map((v) => `${v}: string`).join(', ')} };`);
  lines.push('export interface Outputs { [key: string]: string }');
  lines.push('');
  lines.push('export const steps = {};');
  lines.push('');
  lines.push('export async function runFlow(page: Page, vars: Vars): Promise<Outputs> {');
  lines.push('  const outputs: Outputs = {};');
  lines.push(`  await page.goto(${JSON.stringify(spec.startUrl)});`);
  lines.push('  return outputs;');
  lines.push('}');
  return lines.join('\n');
}

// --- hand-built fixtures ----------------------------------------------------

function segment(id: string, extra: Partial<SpecSegment> = {}): SpecSegment {
  return {
    id,
    template: `do the ${id} thing with {{v1}}`,
    params: { v1: { example: 'foo', usedIn: [1] } },
    preconditions: { urlPattern: 'http://localhost:5173/x' },
    steps: [
      {
        tool: 'click',
        args: { target: '{{v1}}' },
        locators: { target: [{ kind: 'role', role: 'button', name: '{{v1}}', seen: 1 } as any] },
      },
      {
        tool: 'loop',
        args: {},
        locators: {},
        while: [{ kind: 'css', selector: '.row', seen: 1 } as any],
        max: 10,
        body: [
          {
            tool: 'click',
            args: { target: 'Delete' },
            locators: { target: [{ kind: 'text', text: 'Delete', seen: 1 } as any] },
          },
        ],
      },
    ],
    ...extra,
  };
}

function step(id: string, extra: Partial<SpecStep> = {}): SpecStep {
  return {
    id,
    instruction: `Step ${id}`,
    params: { v1: 'literal', v2: '{{someVar}}', v3: '{{01-open.title}}' },
    outputs: ['title'],
    segments: [segment(`${id}-seg`)],
    ...extra,
  };
}

const HAND_BUILT_FLOWS: SpecFlow[] = [
  // minimal: one step, no segments (no converged procedure)
  {
    version: 1,
    name: 'minimal',
    origin: 'http://localhost:5173',
    startUrl: 'http://localhost:5173/',
    vars: [],
    steps: [step('01-open', { segments: [] })],
  },
  // multi-step, multi-segment, with loops/mints/derived
  {
    version: 1,
    name: 'full',
    origin: 'http://localhost:5173',
    startUrl: 'http://localhost:5173/project-manager',
    vars: ['name', 'client'],
    steps: [
      step('01-open', { params: {}, outputs: [] }),
      step('02-create', {
        params: { v1: '{{name}}', v2: '{{client}}' },
        outputs: ['id', 'url'],
        segments: [
          segment('02-create-seg', {
            derived: { d1: { step: 2, at: 'id', example: '42' } },
          }),
        ],
      }),
    ],
  },
  // no steps at all
  {
    version: 1,
    name: 'empty',
    origin: 'http://localhost:5173',
    startUrl: 'http://localhost:5173/',
    vars: [],
    steps: [],
  },
];

function wrapSkillAsFlow(skill: Skill): SpecFlow {
  const derived = skill.derived;
  const segments: SpecSegment[] =
    skill.seq == null || skill.seq.index === 0
      ? [
          {
            id: skill.id,
            template: skill.template,
            params: skill.params,
            preconditions: skill.preconditions.requireText
              ? { urlPattern: skill.preconditions.urlPattern, requireText: skill.preconditions.requireText }
              : { urlPattern: skill.preconditions.urlPattern },
            steps: skill.steps,
            ...(derived ? { derived } : {}),
          },
        ]
      : [];
  return {
    version: 1,
    name: `skill-${skill.id}`,
    origin: skill.origin,
    startUrl: skill.preconditions.urlPattern,
    vars: Object.keys(skill.params),
    steps: [
      {
        id: '01-run',
        instruction: skill.template,
        params: Object.fromEntries(Object.keys(skill.params).map((k) => [k, `{{${k}}}`])),
        outputs: [],
        segments,
      },
    ],
  };
}

const FWAT2_SKILLS_PATH = path.join(__dirname, '..', 'bench', 'results-published', 'fwat2-skills', 'localhost_5173.json');
const fwat2Skills: Skill[] = JSON.parse(fs.readFileSync(FWAT2_SKILLS_PATH, 'utf8'));

describe('liftFlowFile: round trip (test-local emitter layout)', () => {
  it.each(HAND_BUILT_FLOWS.map((spec) => [spec.name, spec] as const))('hand-built spec "%s"', (_name, spec) => {
    const text = buildFlowFileText(spec);
    const { spec: lifted, version } = liftFlowFile(text);
    expect(version).toBe(1);
    expect(lifted).toEqual(spec);
  });

  it('round-trips every skill in the fwat2 store, wrapped as a one-step flow', () => {
    expect(fwat2Skills.length).toBeGreaterThan(0);
    for (const skill of fwat2Skills) {
      const spec = wrapSkillAsFlow(skill);
      const text = buildFlowFileText(spec);
      const { spec: lifted } = liftFlowFile(text);
      expect(lifted).toEqual(spec);
    }
  });
});

describe('liftFlowFile: round trip through the real emitter (when present)', () => {
  it('emitFlowFile → liftFlowFile round-trips, or is skipped if emit.ts is absent', async () => {
    let emitFlowFile: undefined | ((spec: SpecFlow, o: { tier: 'plain' }) => { source: string; warnings: string[] });
    try {
      const mod: any = await import('../src/spec/emit.js');
      emitFlowFile = mod.emitFlowFile;
    } catch {
      emitFlowFile = undefined;
    }
    if (typeof emitFlowFile !== 'function') {
      // emit.ts not landed yet (or doesn't export emitFlowFile) — nothing to test.
      return;
    }
    for (const spec of HAND_BUILT_FLOWS) {
      const { source } = emitFlowFile(spec, { tier: 'plain' });
      const { spec: lifted } = liftFlowFile(source);
      expect(lifted).toEqual(spec);
    }
  });
});

describe('isOwnedFlowFile', () => {
  it('is true for a well-formed emitted file', () => {
    expect(isOwnedFlowFile(buildFlowFileText(HAND_BUILT_FLOWS[0]))).toBe(true);
  });
  it('is false when the header comment is missing', () => {
    expect(isOwnedFlowFile(buildFlowFileText(HAND_BUILT_FLOWS[0], { header: false }))).toBe(false);
  });
  it('is false for an arbitrary file', () => {
    expect(isOwnedFlowFile('export const x = 1;')).toBe(false);
  });
});

describe('liftFlowFile: negative cases (hand-edited files)', () => {
  it('throws LiftError when the begin marker is missing', () => {
    const text = buildFlowFileText(HAND_BUILT_FLOWS[0], { omitBegin: true });
    expect(() => liftFlowFile(text)).toThrow(LiftError);
    expect(() => liftFlowFile(text)).toThrow(/begin/i);
  });

  it('throws LiftError when the end marker is missing', () => {
    const text = buildFlowFileText(HAND_BUILT_FLOWS[0], { omitEnd: true });
    expect(() => liftFlowFile(text)).toThrow(LiftError);
    expect(() => liftFlowFile(text)).toThrow(/end/i);
  });

  it('throws LiftError with a JSON-parse reason on a trailing comma (hand-edited FLOW)', () => {
    const spec = HAND_BUILT_FLOWS[0];
    // Simulate a human editing the emitted JSON literal directly: a trailing
    // comma after the last property, which JSON (unlike JS) rejects.
    const handEditedJson = JSON.stringify(spec, null, 2).replace(/\n\}$/, ',\n}');
    const text = buildFlowFileText(spec, { handEditedJson });
    expect(() => liftFlowFile(text)).toThrow(LiftError);
    expect(() => liftFlowFile(text)).toThrow(/JSON/i);
  });

  it('throws LiftError on an unsupported version', () => {
    const spec2 = { ...HAND_BUILT_FLOWS[0], version: 2 } as unknown as SpecFlow;
    const text = buildFlowFileText(spec2);
    expect(() => liftFlowFile(text)).toThrow(LiftError);
    expect(() => liftFlowFile(text)).toThrow(/version/i);
  });

  it('ignores a stray "export const FLOW" outside the markers and lifts the real one', () => {
    const spec = HAND_BUILT_FLOWS[0];
    const text = buildFlowFileText(spec);
    const withStray = `export const FLOW = "not the real one, someone pasted this by hand";\n${text}\n// another stray:\nexport const FLOW = { version: 999 };\n`;
    const { spec: lifted } = liftFlowFile(withStray);
    expect(lifted).toEqual(spec);
  });

  it('throws LiftError naming the step index and segment id for a shape defect', () => {
    const spec = HAND_BUILT_FLOWS[1];
    const broken = JSON.parse(JSON.stringify(spec));
    broken.steps[1].segments[0].steps[0].tool = 123; // tool must be a string
    const text = buildFlowFileText(broken);
    expect(() => liftFlowFile(text)).toThrow(LiftError);
    expect(() => liftFlowFile(text)).toThrow(/step\[1\]/);
    expect(() => liftFlowFile(text)).toThrow(/02-create-seg/);
  });
});
